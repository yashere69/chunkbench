"""BM25, WordLlama and their fusion on the sample corpus, at top-2 and at a 100-word budget.
Writes results/retrievers.md.

    pip install -e ".[wordllama]"
    python tools/compare_retrievers.py
"""

from __future__ import annotations

import sys
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from chunkbench.bench import evaluate, load_corpus, load_questions  # noqa: E402

STRATEGIES = ["fixed:50,0", "fixed:100,50", "recursive:30", "recursive:60", "headings:120"]
RETRIEVERS = ["bm25", "wordllama", "hybrid:wordllama"]


def pick(rows: list[dict], strategy: str, retriever: str, lang: str) -> dict:
    return next(
        x
        for x in rows
        if x["strategy"] == strategy and x["retriever"] == retriever and x["lang"] == lang
    )


def main() -> None:
    corpus = ROOT / "examples/corpus"
    docs = load_corpus(corpus)
    questions = load_questions(corpus / "questions.yaml", docs)
    by_lang = {lang: sum(q.lang == lang for q in questions) for lang in ("en", "hi")}
    lines = [
        "# Retrievers on the sample corpus",
        "",
        "Generated by `python tools/compare_retrievers.py`. Do not edit by hand.",
        "",
        f"{len(docs)} documents, {len(questions)} questions ({by_lang['en']} English, "
        f"{by_lang['hi']} Hindi), word units. wordllama {version('wordllama')} "
        "(l2_supercat, 256 dimensions). Recall and IoU in %; context is the mean number of "
        "words handed to the reader per question.",
        "",
    ]
    for title, budget in [("Top 2 chunks", None), ("Up to 100 words", 100)]:
        rows = evaluate(docs, questions, STRATEGIES, 2, ["words"], RETRIEVERS, budget)
        lines += [
            f"## {title}",
            "",
            "| Strategy | Retriever | Context | Recall en | Recall hi | IoU en | IoU hi |",
            "|---|---|---|---|---|---|---|",
        ]
        for s in STRATEGIES:
            for r in RETRIEVERS:
                en, hi = pick(rows, s, r, "en"), pick(rows, s, r, "hi")
                lines.append(
                    f"| {s} | {r} | {en['context_words']:.0f} | {en['recall']} | {hi['recall']}"
                    f" | {en['iou']} | {hi['iou']} |"
                )
        lines.append("")
    (ROOT / "results/retrievers.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
